export function detectInitialUiLang(): UiLangCode {
  if (typeof navigator === 'undefined') return 'tr';
  const nav = (navigator.language || 'tr').toLowerCase().slice(0, 2) as UiLangCode;
  if (nav in STRINGS) return nav;
  return 'en';
}

export function getUiStrings(code: UiLangCode): UiStrings {
  return STRINGS[code] || STRINGS.en;
}
